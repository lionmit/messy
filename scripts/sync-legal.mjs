#!/usr/bin/env node
/**
 * Copies MESSY's legal pages, word for word, from the legal cover in messy-sites
 * into src/content/legal.generated.ts. Run it again whenever the legal texts change:
 *
 *   node scripts/sync-legal.mjs [path/to/01-texts.md]
 *
 * Default source: ../messy-sites/board/legal/01-texts.md (the two repos sit side by side).
 * Pages: §א privacy, §ג terms and refunds, §ד accessibility. Each stops at its first "###"
 * (notes for the editor, not page text) or "---".
 *
 * §א.1: until automatic deletion and the private document link are built, the privacy page
 * carries the interim wording from §א.1 instead of the 90-day sentence, and drops the
 * sentence about the private link. It refuses to run if either sentence moved.
 *
 * tests/legal.test.ts imports buildPages() and fails when the generated file is out of date.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

function section(text, letter) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.startsWith(`## ${letter}. `));
  if (start < 0) throw new Error(`section ${letter} not found`);
  const body = [];
  for (const l of lines.slice(start + 1)) {
    if (l.startsWith('## ') || l.startsWith('### ') || l.trim() === '---') break;
    body.push(l);
  }
  return body.join('\n').trim();
}

function interimPrivacy(text, md) {
  const lines = text.split('\n');
  const a1 = lines.findIndex((l) => l.startsWith('### א.1'));
  const quote = a1 < 0 ? undefined : lines.slice(a1).find((l) => l.startsWith('> '));
  if (!quote) throw new Error('§א.1 interim wording not found');
  const ninety = '- השיחה המלאה נמחקת אחרי 90 יום.';
  const link = 'המסמך נשמר כדי שיהיה זמין בקישור. ';
  if (!md.includes(ninety) || !md.includes(link)) throw new Error('§א changed: the §א.1 replacement points no longer match');
  return md.replace(ninety, `- ${quote.slice(2).trim()}`).replace(link, '');
}

/** The three pages from the text of 01-texts.md. */
export function buildPages(raw) {
  const text = raw.replace(/\r\n/g, '\n');
  return {
    privacy: interimPrivacy(text, section(text, 'א')),
    terms: section(text, 'ג'),
    accessibility: section(text, 'ד'),
  };
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const src = resolve(process.argv[2] ?? resolve(here, '..', '..', 'messy-sites', 'board', 'legal', '01-texts.md'));
  const out = resolve(here, '..', 'src', 'content', 'legal.generated.ts');
  const raw = readFileSync(src, 'utf8');
  const sha256 = createHash('sha256').update(raw.replace(/\r\n/g, '\n')).digest('hex').slice(0, 12);
  writeFileSync(
    out,
    `// Generated by scripts/sync-legal.mjs from messy-sites/board/legal/01-texts.md. Do not edit by hand.\n` +
      `// §א with the §א.1 interim wording, §ג and §ד, word for word. ⟦…⟧ marks a detail still missing.\n` +
      `export const LEGAL_SOURCE = ${JSON.stringify({ file: 'messy-sites/board/legal/01-texts.md', sha256 })} as const;\n\n` +
      `export const LEGAL = ${JSON.stringify(buildPages(raw), null, 2)} as const;\n`,
    'utf8'
  );
  console.log(`wrote ${out} from ${src} (sha256 ${sha256})`);
}
